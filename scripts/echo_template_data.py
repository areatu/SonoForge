"""Local synthetic/gold adapters for ML.3; no external datasets or implicit scans."""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
import pydicom

from echo_personal_tool.domain.services.cardiac_atlas import CoupledShapeModel
from echo_personal_tool.domain.services.cardiac_atlas_geometry import resample_arc
from echo_personal_tool.domain.services.echo_template_contract import (
    MAX_TEMPLATE_NODES,
    TEMPLATE_LANDMARKS,
    TEMPLATE_VIEWS,
    points_to_crop,
    prepare_template_input,
)
from echo_personal_tool.domain.services.gold_store import load_gold


@dataclass
class TemplateSample:
    path: Path
    frame_index: int
    view: str
    phase: str
    group_id: str
    source: str
    split: str = ""
    contours: dict[str, np.ndarray] = field(default_factory=dict)
    landmarks: dict[str, np.ndarray] = field(default_factory=dict)


def load_synthetic_samples(manifest_path: Path) -> list[TemplateSample]:
    root = manifest_path.resolve().parent
    manifest = json.loads(manifest_path.read_text())
    if manifest.get("schema_version") != 2 or tuple(manifest.get("class_names", ())) != TEMPLATE_VIEWS:
        raise ValueError("unsupported synthetic manifest")
    entries = {entry["sample_id"]: entry for entry in manifest["samples"]}
    if len(entries) != len(manifest["samples"]):
        raise ValueError("duplicate synthetic sample id")
    generation = json.loads((root / "generation.json").read_text())
    if set(entries) != {record["sample_id"] for record in generation["records"]}:
        raise ValueError("manifest/generation sample mismatch")
    samples = []
    for record in generation["records"]:
        key = record["sample_id"]
        view = record["config"]["view"]
        if entries[key]["view"] != view or entries[key]["split"] != record["split"]:
            raise ValueError("manifest/generation view or split mismatch")
        # IDs generated by ML.2 are basenames; do not allow paths out of corpus.
        if Path(key).name != key or "/" in key or "\\" in key:
            raise ValueError("invalid synthetic sample id")
        path = root / "clips" / f"{key}.dcm"
        with np.load(root / "truth" / f"{key}.npz", allow_pickle=False) as truth:
            for phase, index in (("ED", record["ed_frame"]), ("ES", record["es_frame"])):
                contours = {
                    name.removeprefix("contour_"): truth[name][index].copy()
                    for name in truth.files
                    if name.startswith("contour_")
                }
                landmarks = {
                    name.removeprefix("landmark_"): truth[name][index].copy()
                    for name in truth.files
                    if name.startswith("landmark_")
                }
                if "LA_apex" in landmarks:
                    landmarks["LA_roof"] = landmarks.pop("LA_apex")
                if "MV_septal" in landmarks and "TV_septal" in landmarks:
                    landmarks["crux"] = (landmarks["MV_septal"] + landmarks["TV_septal"]) / 2
                samples.append(
                    TemplateSample(
                        path, index, view, phase, record["subject"], "synthetic", record["split"], contours, landmarks
                    )
                )
    return samples


def load_gold_samples(paths: list[Path]) -> list[TemplateSample]:
    merged: dict[tuple[str, int, str, str], TemplateSample] = {}
    for path in paths:
        gold = load_gold(path)
        group = str(gold.get("patient_group_id") or gold.get("study_uid") or gold["study_id"])
        for frame in gold["frames"]:
            view = str(frame.get("view", gold.get("view", ""))).upper()
            if view not in TEMPLATE_VIEWS:
                raise ValueError("gold needs a supported reviewed view")
            source = Path(frame.get("instance_path") or gold.get("instance_path", ""))
            if not source.is_absolute():
                source = path.parent / source
            if not source.is_file():
                raise ValueError("gold source DICOM is missing")
            key = (str(source.resolve()), int(frame["frame_index"]), view, frame["phase"])
            sample = merged.setdefault(
                key, TemplateSample(source, key[1], view, key[3], group, "gold", str(gold.get("split", "")))
            )
            if sample.group_id != group or sample.split != str(gold.get("split", "")):
                raise ValueError("inconsistent gold group/split")
            chamber = str(frame.get("chamber", gold.get("chamber", "LV"))).upper()
            if chamber not in {"LV", "LA", "RV", "RA"}:
                continue
            if chamber in sample.contours:
                raise ValueError("duplicate chamber/frame gold; curate revisions first")
            sample.contours[chamber] = np.asarray(frame["points"], dtype=float)
            # gold_store uses generic mitral_annulus for every open arc, including TV.
            annulus = (
                frame.get("tricuspid_annulus", frame.get("mitral_annulus"))
                if chamber == "RV"
                else frame.get("mitral_annulus")
                if chamber in {"LV", "LA"}
                else None
            )
            prefix = "MV" if chamber in {"LV", "LA"} else "TV"
            if annulus is not None:
                sample.landmarks[f"{prefix}_septal"], sample.landmarks[f"{prefix}_lateral"] = np.asarray(
                    annulus, dtype=float
                )
            if chamber != "RA" and frame.get("apex_landmark") is not None:
                name = "LA_roof" if chamber == "LA" else f"{chamber}_apex"
                sample.landmarks[name] = np.asarray(frame["apex_landmark"], dtype=float)
    return list(merged.values())


def load_measurement_corpus(path: Path) -> list[TemplateSample]:
    """Explicit reviewed LOCAL export; no implicit gold promotion or DICOM reads.

    The archived split_group is already unioned by patient/study/pixels. Never
    recalculate it by clip. RA stays archived but this adapter rejects it
    explicitly until a reviewed RA training contract is supplied.
    """
    from echo_personal_tool.domain.services.training_archive import atlas_phase

    manifest = json.loads(path.read_text())
    if manifest.get("format") != "local_measurement_segmentation_corpus" or manifest.get("schema_version") != 1:
        raise ValueError("unsupported measurement corpus")
    samples = []
    for record in manifest["records"]:
        if (
            not record["reviewed"]
            or not record["strong_label"]
            or record["geometry_kind"] != "trace"
            or record.get("excluded")
        ):
            continue
        if record["chamber"] == "RA":
            raise ValueError("RA archive supported; training adapter not yet supported")
        if record["view"] not in TEMPLATE_VIEWS or record["split"] not in {"train", "val", "test"}:
            raise ValueError("unsupported corpus view/split")
        source = (path.parent / record["image"]).resolve()
        if source.parent != path.parent.resolve() or source.suffix != ".npy" or not source.is_file():
            raise ValueError("invalid local corpus frame")
        sample = TemplateSample(
            source,
            0,
            record["view"],
            atlas_phase(record["phase_semantics"]),
            record["split_group"],
            "gold",
            record["split"],
            {record["chamber"]: np.asarray(record["points"], dtype=float)},
        )
        annulus, apex = record["mitral_annulus"], record["apex_landmark"]
        if annulus is None or apex is None:
            raise ValueError(
                "node training requires reviewed open arcs and landmarks; polygon remains in segmentation corpus"
            )
        prefix = "TV" if record["chamber"] == "RV" else "MV"
        if annulus is not None:
            sample.landmarks[f"{prefix}_septal"], sample.landmarks[f"{prefix}_lateral"] = np.asarray(
                annulus, dtype=float
            )
        if apex is not None:
            name = "LA_roof" if record["chamber"] == "LA" else f"{record['chamber']}_apex"
            sample.landmarks[name] = np.asarray(apex, dtype=float)
        samples.append(sample)
    return samples


def assign_group_splits(samples: list[TemplateSample], *, seed: int = 0) -> None:
    groups: dict[str, str] = {}
    # Explicit assignments take precedence for the ENTIRE group, across data sources.
    for sample in samples:
        if sample.split:
            if sample.split not in {"train", "val", "test"}:
                raise ValueError("invalid split")
            if sample.group_id in groups and groups[sample.group_id] != sample.split:
                raise ValueError("group leakage across splits")
            groups[sample.group_id] = sample.split
    for sample in samples:
        if sample.group_id not in groups:
            bucket = int(hashlib.sha256(f"{seed}:{sample.group_id}".encode()).hexdigest()[:8], 16) % 10
            groups[sample.group_id] = "test" if bucket == 9 else "val" if bucket >= 7 else "train"
        sample.split = groups[sample.group_id]
    instances: dict[str, tuple[str, str]] = {}
    for sample in samples:
        key = str(sample.path.resolve())
        identity = (sample.group_id, sample.split)
        if key in instances and instances[key] != identity:
            raise ValueError("same instance assigned to different groups/splits")
        instances[key] = identity


def training_target(sample: TemplateSample, model: CoupledShapeModel, transform, input_size: int) -> dict[str, Any]:
    nodes = np.zeros((MAX_TEMPLATE_NODES, 2), dtype=np.float32)
    observed = np.zeros(MAX_TEMPLATE_NODES, dtype=bool)
    for name, arc in sample.contours.items():
        if name not in model.structures or name == "IVS":
            continue
        ids = list(model.structures[name])
        if not np.isfinite(arc).all():
            raise ValueError("nonfinite gold contour")
        points = arc if len(arc) == len(ids) else resample_arc(arc, len(ids), closed=name in model.closed_structures)
        normalized = points_to_crop(points, transform)
        common = observed[ids]
        if common.any() and np.max(
            np.linalg.norm(nodes[np.asarray(ids)[common]] - normalized[common], axis=1)
        ) > 3 / max(transform.crop_width, transform.crop_height):
            raise ValueError("contradictory shared gold nodes")
        nodes[ids], observed[ids] = normalized, True
    heat_size = input_size // 4
    heatmaps = np.zeros((9, heat_size, heat_size), dtype=np.float32)
    visible, known = np.zeros(9, dtype=np.float32), np.zeros(9, dtype=np.float32)
    yy, xx = np.mgrid[:heat_size, :heat_size]
    for i, name in enumerate(TEMPLATE_LANDMARKS):
        if name in sample.landmarks:
            point = points_to_crop(np.asarray([sample.landmarks[name]]), transform)[0]
            if np.isfinite(point).all() and np.all(point >= 0) and np.all(point <= 1):
                x, y = point * (heat_size - 1)
                heatmaps[i] = np.exp(-((xx - x) ** 2 + (yy - y) ** 2) / (2 * 1.5**2))
                visible[i] = known[i] = 1
        elif sample.source == "synthetic":
            known[i] = 1  # Known absent in synthetic geometry, not missing gold annotation.
    return {
        "nodes": nodes,
        "node_mask": observed,
        "heatmaps": heatmaps,
        "visible": visible,
        "visibility_mask": known,
        "view": TEMPLATE_VIEWS.index(sample.view) if sample.view in TEMPLATE_VIEWS else -1,
        "phase": 0 if sample.phase == "ED" else 1,
    }


class TemplateDataset:
    def __init__(self, samples: list[TemplateSample], atlases: dict[str, CoupledShapeModel], *, input_size: int = 224):
        self.samples, self.atlases, self.input_size = samples, atlases, input_size

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, index):
        sample = self.samples[index]
        if sample.path.suffix == ".npy":
            pixels = np.load(sample.path, allow_pickle=False)
            if pixels.ndim not in {2, 3} or pixels.dtype.kind not in "uif" or pixels.nbytes > 128 * 1024**2:
                raise ValueError("invalid local corpus frame")
            total_frames = 1
        else:
            ds = pydicom.dcmread(sample.path)
            pixels = ds.pixel_array
            total_frames = int(getattr(ds, "NumberOfFrames", 1))
        if total_frames > 1:
            if not 0 <= sample.frame_index < len(pixels):
                raise ValueError("gold frame outside cine")
            frame = pixels[sample.frame_index]
        else:
            if sample.frame_index != 0:
                raise ValueError("gold frame outside single image")
            frame = pixels
        tensor, transform = prepare_template_input(frame, input_size=self.input_size)
        model = self.atlases.get(sample.view, self.atlases["A4C"])
        target = training_target(sample, model, transform, self.input_size)
        if sample.view == "UNKNOWN":
            target["node_mask"][:] = False
            target["visibility_mask"][:] = 0
        return {"image": tensor[0], **target}


class RVGoldDataset(TemplateDataset):
    """RV training adapter; retains coupled LV/LA labels when actually observed."""

    def __init__(self, samples, atlases, *, input_size=224):
        selected = [sample for sample in samples if "RV" in sample.contours and sample.view in {"A4C", "RV_A4C"}]
        super().__init__(selected, atlases, input_size=input_size)
